export function translateGanZhi(chineseStr: string): string {
  if (!chineseStr || chineseStr.length < 2) return chineseStr;
  const can = CAN_NAMES[chineseStr[0]] || chineseStr[0];
  const chi = CHI_NAMES[chineseStr[1]] || chineseStr[1];
  return `${can} ${chi}`;
}
